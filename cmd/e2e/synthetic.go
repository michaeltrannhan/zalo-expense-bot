// syntheticReceiptPNG produces a privacy-safe, deterministic image for a
// live Gemini OCR smoke. The bitmap font keeps the fixture portable across
// macOS/Linux and avoids adding a font-rendering dependency.
func syntheticReceiptPNG() ([]byte, error) {
	canvas := image.NewRGBA(image.Rect(0, 0, 900, 600))
	draw.Draw(canvas, canvas.Bounds(), image.NewUniform(color.White), image.Point{}, draw.Src)
	ink := color.RGBA{R: 20, G: 25, B: 35, A: 255}
	muted := color.RGBA{R: 105, G: 115, B: 125, A: 255}
	fillRect(canvas, image.Rect(34, 34, 866, 40), ink)
	fillRect(canvas, image.Rect(34, 560, 866, 566), ink)
	fillRect(canvas, image.Rect(34, 34, 40, 566), ink)
	fillRect(canvas, image.Rect(860, 34, 866, 566), ink)
	drawBitmapText(canvas, 100, 82, "CODEX E2E CAFE", 7, ink)
	drawBitmapText(canvas, 195, 165, "TEST RECEIPT", 6, muted)
	fillRect(canvas, image.Rect(92, 245, 808, 249), muted)
	drawBitmapText(canvas, 105, 292, "DATE 2026-08-12", 6, ink)
	drawBitmapText(canvas, 105, 382, "TOTAL 123,456 VND", 7, ink)
	var out bytes.Buffer
	if err := png.Encode(&out, canvas); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}

func fillRect(dst draw.Image, rect image.Rectangle, c color.Color) {
	draw.Draw(dst, rect, image.NewUniform(c), image.Point{}, draw.Src)
}

func drawBitmapText(dst draw.Image, x, y int, text string, scale int, c color.Color) {
	cursor := x
	for _, char := range strings.ToUpper(text) {
		glyph, ok := bitmapFont[char]
		if !ok {
			glyph = bitmapFont['?']
		}
		for row, pixels := range glyph {
			for col, pixel := range pixels {
				if pixel == '1' {
					fillRect(dst, image.Rect(
						cursor+col*scale, y+row*scale,
						cursor+(col+1)*scale, y+(row+1)*scale,
					), c)
				}
			}
		}
		cursor += 6 * scale
	}
}

